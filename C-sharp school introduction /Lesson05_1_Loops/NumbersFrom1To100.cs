namespace C_sharp_school_introduction.Lesson05_1_Loops;

// Example: Numbers from 1 to 100
// Print the numbers from 1 to 100, each on a new line.
public static class NumbersFrom1To100
{
    public static void Run()
    {
        for (int i = 1; i <= 100; i++)
        {
            Console.WriteLine(i);
        }
    }
}
